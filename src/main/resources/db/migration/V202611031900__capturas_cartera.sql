-- Copias históricas independientes de padrón, deuda y usuario: una sincronización no las sobrescribe.
CREATE TABLE capturas_cartera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    usuario VARCHAR(255) NOT NULL
);
CREATE TABLE captura_cuentas (
    captura_id BIGINT NOT NULL REFERENCES capturas_cartera(id),
    cm VARCHAR(50) NOT NULL,
    origen VARCHAR(20) NOT NULL CHECK (origen IN ('INTENDENCIA','SUCIVE')),
    numero_padron VARCHAR(255), tipo_padron VARCHAR(255), nombre TEXT, documento VARCHAR(255),
    importe NUMERIC(19,2) NOT NULL CHECK (importe >= 0),
    estado VARCHAR(40) NOT NULL, segmento VARCHAR(255),
    fecha_sincronizacion TIMESTAMP, fecha_ultimo_cobro DATE, importe_ultimo_cobro NUMERIC(19,2),
    PRIMARY KEY(captura_id,origen,cm)
);
CREATE INDEX idx_capturas_fecha ON capturas_cartera(fecha DESC,id DESC);
