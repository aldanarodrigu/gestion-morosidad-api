CREATE TABLE cancelaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen VARCHAR(20) NOT NULL CHECK (origen IN ('INTENDENCIA', 'SUCIVE')),
    cm TEXT NOT NULL,
    numero_cobro TEXT NOT NULL,
    numero_padron TEXT,
    persona TEXT,
    documento TEXT,
    fecha_cobro DATE NOT NULL,
    importe_total NUMERIC,
    motivo TEXT,
    detectada_en TIMESTAMP NOT NULL,
    UNIQUE (origen, cm, numero_cobro)
);

CREATE INDEX idx_cancelaciones_fecha ON cancelaciones (fecha_cobro DESC, id DESC);
CREATE INDEX idx_cancelaciones_origen_fecha ON cancelaciones (origen, fecha_cobro DESC, id DESC);
